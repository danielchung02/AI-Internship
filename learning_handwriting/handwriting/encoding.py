def decompose(ch: str):
    """Return (initial, vowel, final) indices, or None for non-Hangul."""
    if len(ch) != 1 or not ('가' <= ch <= '힣'):
        return None
    n = ord(ch) - ord('가')
    return n // 588 + 1, (n % 588) // 28 + 1, n % 28
